-- 用已有审计记录回填员工建档时间与最近操作人
UPDATE employee e
JOIN (SELECT object_id, MIN(occurred_at) AS created FROM audit_event
      WHERE operation = 'EMPLOYEE_CREATE' GROUP BY object_id) history ON history.object_id = e.id
SET e.created_at = history.created;

UPDATE employee e
JOIN (SELECT object_id, actor_id FROM audit_event
      WHERE id IN (SELECT MAX(id) FROM audit_event
                   WHERE operation IN ('EMPLOYEE_CREATE', 'EMPLOYEE_UPDATE', 'EMPLOYEE_DEPART')
                   GROUP BY object_id)) latest ON latest.object_id = e.id
SET e.updated_by = latest.actor_id;